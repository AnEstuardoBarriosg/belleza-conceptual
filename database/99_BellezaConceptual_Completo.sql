CREATE OR REPLACE VIEW vw_catalogo_productos AS
SELECT
    p.id_producto,
    p.nombre AS producto,
    c.id_categoria,
    c.nombre AS categoria,
    p.descripcion,
    p.precio,
    COALESCE(i.cantidad_disponible, 0) AS cantidad_disponible,
    (COALESCE(i.cantidad_disponible, 0) > 0) AS disponible,
    img.url_imagen AS imagen_principal
FROM producto p
JOIN categoria c
  ON c.id_categoria = p.id_categoria
LEFT JOIN inventario i
  ON i.id_producto = p.id_producto
LEFT JOIN LATERAL (
    SELECT ip.url_imagen
      FROM imagen_producto ip
     WHERE ip.id_producto = p.id_producto
     ORDER BY ip.es_principal DESC, ip.id_imagen ASC
     LIMIT 1
) img ON TRUE
WHERE p.estado_activo = TRUE
  AND c.estado = TRUE;

CREATE OR REPLACE VIEW vw_inventario_actual AS
SELECT
    i.id_inventario,
    p.id_producto,
    p.nombre AS producto,
    c.nombre AS categoria,
    i.cantidad_disponible,
    i.ultima_actualizacion,
    p.estado_activo
FROM inventario i
JOIN producto p
  ON p.id_producto = i.id_producto
JOIN categoria c
  ON c.id_categoria = p.id_categoria;

CREATE OR REPLACE VIEW vw_pedidos_resumen AS
SELECT
    p.id_pedido,
    p.codigo_pedido,
    p.fecha_pedido,
    c.id_cliente,
    c.nombre AS cliente,
    c.telefono,
    c.email,
    p.total,
    p.estado_actual,
    p.metodo_pago_preferido,
    pg.estado_pago,
    pg.monto AS monto_pago,
    e.tipo_envio,
    e.estado_entrega,
    e.fecha_coordinada
