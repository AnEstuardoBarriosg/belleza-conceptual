CREATE OR REPLACE FUNCTION tg_calcular_subtotal_carrito()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_precio NUMERIC(10,2);
BEGIN
    SELECT precio
      INTO v_precio
      FROM producto
     WHERE id_producto = NEW.id_producto
       AND estado_activo = TRUE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'El producto % no existe o está inactivo', NEW.id_producto;
    END IF;

    NEW.subtotal := ROUND(v_precio * NEW.cantidad, 2);
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_linea_carrito_subtotal
BEFORE INSERT OR UPDATE OF id_producto, cantidad
ON linea_carrito
FOR EACH ROW
EXECUTE FUNCTION tg_calcular_subtotal_carrito();

CREATE OR REPLACE FUNCTION tg_preparar_detalle_pedido()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_precio NUMERIC(10,2);
BEGIN
    IF TG_OP = 'INSERT'
       OR NEW.id_producto IS DISTINCT FROM OLD.id_producto THEN

        SELECT precio
          INTO v_precio
          FROM producto
         WHERE id_producto = NEW.id_producto
           AND estado_activo = TRUE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'El producto % no existe o está inactivo', NEW.id_producto;
        END IF;

        NEW.precio_unitario := v_precio;
    END IF;

    NEW.subtotal := ROUND(NEW.precio_unitario * NEW.cantidad, 2);
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_detalle_pedido_preparar
BEFORE INSERT OR UPDATE OF id_producto, cantidad
ON detalle_pedido
FOR EACH ROW
EXECUTE FUNCTION tg_preparar_detalle_pedido();

CREATE OR REPLACE FUNCTION tg_recalcular_total_pedido()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        UPDATE pedido
           SET total = fn_calcular_total_pedido(OLD.id_pedido)
         WHERE id_pedido = OLD.id_pedido;
        RETURN OLD;
    END IF;

    UPDATE pedido
       SET total = fn_calcular_total_pedido(NEW.id_pedido)
     WHERE id_pedido = NEW.id_pedido;

    IF TG_OP = 'UPDATE' AND OLD.id_pedido IS DISTINCT FROM NEW.id_pedido THEN
        UPDATE pedido
           SET total = fn_calcular_total_pedido(OLD.id_pedido)
         WHERE id_pedido = OLD.id_pedido;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_detalle_pedido_total
AFTER INSERT OR UPDATE OR DELETE
ON detalle_pedido
FOR EACH ROW
EXECUTE FUNCTION tg_recalcular_total_pedido();

CREATE OR REPLACE FUNCTION tg_actualizar_fecha_inventario()
