CREATE OR REPLACE FUNCTION fn_stock_disponible(p_id_producto INT)
RETURNS INT
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_stock INT;
BEGIN
    SELECT cantidad_disponible
      INTO v_stock
      FROM belleza_conceptual.inventario
     WHERE id_producto = p_id_producto;

    RETURN COALESCE(v_stock, 0);
END;
$$;

CREATE OR REPLACE FUNCTION fn_calcular_total_pedido(p_id_pedido INT)
RETURNS NUMERIC(10,2)
LANGUAGE sql
STABLE
AS $$
    SELECT COALESCE(SUM(subtotal), 0.00)::NUMERIC(10,2)
      FROM detalle_pedido
     WHERE id_pedido = p_id_pedido;
$$;

CREATE OR REPLACE FUNCTION fn_generar_codigo_pedido()
RETURNS VARCHAR(30)
LANGUAGE plpgsql
VOLATILE
AS $$
DECLARE
    v_numero BIGINT;
BEGIN
    v_numero := nextval('belleza_conceptual.seq_codigo_pedido');

    RETURN 'PED-' ||
           TO_CHAR(CURRENT_DATE, 'YYYY') ||
           '-' ||
           LPAD(v_numero::TEXT, 4, '0');
END;
$$;

