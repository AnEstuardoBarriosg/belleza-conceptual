CREATE OR REPLACE PROCEDURE sp_crear_pedido(
    IN p_id_cliente INT,
    IN p_metodo_pago VARCHAR(50),
    IN p_items JSONB,
    INOUT p_id_pedido INT,
    INOUT p_codigo_pedido VARCHAR(30)
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_item JSONB;
    v_id_producto INT;
    v_cantidad INT;
    v_stock INT;
BEGIN
    IF p_items IS NULL
       OR jsonb_typeof(p_items) <> 'array'
       OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'El pedido debe contener al menos un producto';
    END IF;

    IF p_metodo_pago NOT IN (
        'Enlace de pago',
        'Transferencia/Deposito',
        'Contra entrega'
    ) THEN
        RAISE EXCEPTION 'Método de pago no válido: %', p_metodo_pago;
    END IF;

    IF NOT EXISTS (
        SELECT 1
          FROM cliente
         WHERE id_cliente = p_id_cliente
    ) THEN
        RAISE EXCEPTION 'El cliente % no existe', p_id_cliente;
    END IF;

    p_codigo_pedido := fn_generar_codigo_pedido();

    INSERT INTO pedido (
        id_cliente,
        codigo_pedido,
        metodo_pago_preferido
    )
    VALUES (
        p_id_cliente,
        p_codigo_pedido,
        p_metodo_pago
    )
    RETURNING id_pedido INTO p_id_pedido;

    FOR v_item IN
        SELECT value
          FROM jsonb_array_elements(p_items)
    LOOP
        v_id_producto := (v_item ->> 'id_producto')::INT;
        v_cantidad := (v_item ->> 'cantidad')::INT;

        IF v_id_producto IS NULL OR v_cantidad IS NULL OR v_cantidad <= 0 THEN
            RAISE EXCEPTION 'Item inválido dentro del pedido: %', v_item;
        END IF;

        IF NOT EXISTS (
            SELECT 1
              FROM producto
             WHERE id_producto = v_id_producto
               AND estado_activo = TRUE
        ) THEN
            RAISE EXCEPTION 'El producto % no existe o está inactivo', v_id_producto;
        END IF;

        v_stock := belleza_conceptual.fn_stock_disponible(v_id_producto);

        IF v_stock < v_cantidad THEN
            RAISE EXCEPTION
                'Stock insuficiente para producto %. Disponible: %, solicitado: %',
                v_id_producto, v_stock, v_cantidad;
        END IF;

        INSERT INTO detalle_pedido (
            id_pedido,
            id_producto,
            cantidad,
            precio_unitario,
            subtotal
        )
        VALUES (
            p_id_pedido,
            v_id_producto,
            v_cantidad,
            0,
            0
        );
    END LOOP;
END;
$$;

CREATE OR REPLACE PROCEDURE sp_registrar_movimiento_inventario(
    IN p_id_producto INT,
    IN p_id_usuario INT,
    IN p_tipo_movimiento VARCHAR(20),
    IN p_cantidad INT,
    IN p_motivo VARCHAR(255)
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_id_inventario INT;
    v_stock_actual INT;
    v_nuevo_stock INT;
    v_movimiento INT;
BEGIN
    IF p_tipo_movimiento NOT IN ('ENTRADA', 'SALIDA', 'AJUSTE') THEN
        RAISE EXCEPTION 'Tipo de movimiento no válido: %', p_tipo_movimiento;
    END IF;

    IF p_cantidad = 0 THEN
        RAISE EXCEPTION 'La cantidad no puede ser cero';
    END IF;

    IF NOT EXISTS (
        SELECT 1
          FROM usuario
         WHERE id_usuario = p_id_usuario
           AND estado = TRUE
    ) THEN
        RAISE EXCEPTION 'Usuario % inexistente o inactivo', p_id_usuario;
    END IF;

    SELECT id_inventario, cantidad_disponible
      INTO v_id_inventario, v_stock_actual
      FROM inventario
     WHERE id_producto = p_id_producto
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No existe inventario para el producto %', p_id_producto;
    END IF;

    CASE p_tipo_movimiento
        WHEN 'ENTRADA' THEN
            v_movimiento := ABS(p_cantidad);
            v_nuevo_stock := v_stock_actual + v_movimiento;

        WHEN 'SALIDA' THEN
            v_movimiento := -ABS(p_cantidad);
            v_nuevo_stock := v_stock_actual + v_movimiento;

        WHEN 'AJUSTE' THEN
            v_movimiento := p_cantidad;
            v_nuevo_stock := v_stock_actual + v_movimiento;
    END CASE;

    IF v_nuevo_stock < 0 THEN
        RAISE EXCEPTION
            'La operación dejaría inventario negativo. Stock actual: %, movimiento: %',
            v_stock_actual, v_movimiento;
    END IF;

    UPDATE inventario
       SET cantidad_disponible = v_nuevo_stock
     WHERE id_inventario = v_id_inventario;

    INSERT INTO movimiento_inventario (
        id_inventario,
        id_usuario,
        tipo_movimiento,
        cantidad,
        motivo
    )
    VALUES (
        v_id_inventario,
        p_id_usuario,
        p_tipo_movimiento,
        v_movimiento,
        p_motivo
    );
END;
$$;

CREATE OR REPLACE PROCEDURE sp_cambiar_estado_pedido(
    IN p_id_pedido INT,
    IN p_id_usuario INT,
    IN p_nuevo_estado VARCHAR(30),
    IN p_observaciones TEXT DEFAULT NULL
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_nuevo_estado NOT IN (
        'Pendiente',
        'En Coordinacion',
        'Pagado',
        'Enviado',
        'Completado',
        'Cancelado'
    ) THEN
        RAISE EXCEPTION 'Estado no válido: %', p_nuevo_estado;
    END IF;

    IF NOT EXISTS (
        SELECT 1
          FROM usuario
         WHERE id_usuario = p_id_usuario
           AND estado = TRUE
    ) THEN
        RAISE EXCEPTION 'Usuario % inexistente o inactivo', p_id_usuario;
    END IF;

    UPDATE pedido
       SET estado_actual = p_nuevo_estado
     WHERE id_pedido = p_id_pedido;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Pedido % no encontrado', p_id_pedido;
    END IF;

    INSERT INTO seguimiento_estado (
        id_pedido,
        id_usuario,
        estado,
        observaciones
    )
    VALUES (
        p_id_pedido,
        p_id_usuario,
        p_nuevo_estado,
        p_observaciones
    );
END;
$$;

CREATE OR REPLACE PROCEDURE sp_registrar_pago(
    IN p_id_pedido INT,
    IN p_metodo_pago VARCHAR(50),
    IN p_monto NUMERIC(10,2),
    IN p_referencia VARCHAR(100),
    IN p_estado_pago VARCHAR(30)
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_metodo_pago NOT IN (
        'Enlace de pago',
        'Transferencia/Deposito',
        'Contra entrega'
    ) THEN
        RAISE EXCEPTION 'Método de pago no válido: %', p_metodo_pago;
    END IF;

    IF p_estado_pago NOT IN ('Pendiente', 'Verificado', 'Rechazado') THEN
        RAISE EXCEPTION 'Estado de pago no válido: %', p_estado_pago;
    END IF;

    IF p_monto < 0 THEN
        RAISE EXCEPTION 'El monto no puede ser negativo';
    END IF;

    IF NOT EXISTS (
        SELECT 1
          FROM pedido
         WHERE id_pedido = p_id_pedido
    ) THEN
        RAISE EXCEPTION 'Pedido % no encontrado', p_id_pedido;
    END IF;

    INSERT INTO pago (
        id_pedido,
        metodo_pago,
        monto,
        referencia,
        estado_pago,
        fecha_pago
    )
    VALUES (
        p_id_pedido,
        p_metodo_pago,
        p_monto,
        p_referencia,
        p_estado_pago,
        CASE
            WHEN p_estado_pago = 'Verificado' THEN CURRENT_TIMESTAMP
            ELSE NULL
        END
    )
    ON CONFLICT (id_pedido)
    DO UPDATE SET
        metodo_pago = EXCLUDED.metodo_pago,
        monto = EXCLUDED.monto,
        referencia = EXCLUDED.referencia,
        estado_pago = EXCLUDED.estado_pago,
        fecha_pago = CASE
            WHEN EXCLUDED.estado_pago = 'Verificado'
                THEN CURRENT_TIMESTAMP
            ELSE pago.fecha_pago
        END;
END;
